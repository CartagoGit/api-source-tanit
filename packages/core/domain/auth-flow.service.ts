// Login body
// ---------------------------------------------------------------------------

/**
 * Leaves the login body with credentials pointing to the environment,
 * **without replacing anything that is not a credential**.
 *
 * `useCredentialVariables` (the version it replaced) had a destructive case:
 * when the body did not include `username`/`email`/`password`, it overwrote
 * the entire body with an invented pair. That broke OAuth2 logins with
 * `grant_type`/`client_id`/`client_secret`, OTP flows, `tenant`/`apiKey`
 * forms, and any login the scanner had described with its real fields.
 *
 * This version (`a00012 S3.b`) follows three rules:
 *
 *   1. It only patches keys already in the body whose value is a `string`.
 *      Numeric, boolean, or `null` values are respected: the user probably
 *      knows what they are doing.
 *   2. It never replaces the entire body. If it finds no credentials, it
 *      leaves the body as-is and warns with `warnMissingCredentials`. The
 *      caller decides whether to show the warning to the user, skip login, or
 *      do something else.
 *   3. If it finds both keys (`username`/`password` or `email`/`password`), it
 *      writes the `{{...}}` placeholders over them. Everything else in the
 *      body (extra fields the scanner recognized) is preserved.
 *
 * For an empty or non-JSON login body, the behavior is identical: nothing
 * is invented, and a warning is emitted.
 */
function attachCredentialTemplate(login: PostmanItem): void {
  const request = login.request;
  if (!request) return;

  const parsed = parseJsonObject(request.body?.raw);
  if (!parsed) {
    warnMissingCredentials({
      reason: "no-json-body",
      path: request.url?.raw ?? "",
    });
    return;
  }

  const usernameKey = findStringField(parsed, USERNAME_FIELDS);
  const passwordKey = findStringField(parsed, PASSWORD_FIELDS);
  if (!usernameKey || !passwordKey) {
    warnMissingCredentials({
      reason: "no-credential-keys",
      path: request.url?.raw ?? "",
      keys: Object.keys(parsed),
    });
    return;
  }

  // Patches only credential keys and leaves everything else intact.
  parsed[usernameKey] = `{{${AUTH_USERNAME_VARIABLE}}}`;
  parsed[passwordKey] = `{{${AUTH_PASSWORD_VARIABLE}}}`;
  writeJsonBody(login, parsed);
}

/**
 * The first key in the object that appears in `candidates` (case-insensitive)
 * **and whose value is a `string`**. If the body has `email: 1` (a scanner
 * that filled it with a numeric placeholder), it is not considered a
 * credential: it is respected.
 */
function findStringField(
  body: Record<string, unknown>,
  candidates: ReadonlyArray<string>,
): string | undefined {
  for (const key of Object.keys(body)) {
    if (!candidates.includes(key.toLowerCase())) continue;
    if (typeof body[key] !== "string") continue;
    return key;
  }
  return undefined;
}

/**
 * Emits a structured warning when the login body does not expose recognizable
 * credentials. The function is exported for tests and so a caller can
 * redirect it if another sink is needed.
 *
 * The warning type lives in
 * `packages/contracts/interfaces/cli/auth-warning.interface.ts`; defining it
 * here would pull this service in just to type it, which is exactly what
 * `lint:contracts` prohibits.
 */
export function warnMissingCredentials(
  warning: Omit<IMissingCredentialsWarning, "kind">,
): void {
  const payload: IMissingCredentialsWarning = { kind: "missing-credentials", ...warning };
  console.warn(JSON.stringify(payload));
}

function parseJsonObject(raw: string | undefined): Record<string, unknown> | null {
  if (!raw) return null;
  try {
    const parsed: unknown = JSON.parse(raw);
    if (!parsed || typeof parsed !== "object" || Array.isArray(parsed)) return null;
    return parsed as Record<string, unknown>;
  } catch {
    return null;
  }
}

function writeJsonBody(item: PostmanItem, body: Record<string, unknown>): void {
  if (!item.request) return;
  item.request.body = {
    mode: "raw",
    raw: JSON.stringify(body, null, 2),
    options: { raw: { language: "json" } },
  };
  const hasContentType = item.request.header.some(
    (h) => h.key.toLowerCase() === "content-type",
  );
  if (!hasContentType) {
    item.request.header.push({ key: "Content-Type", value: "application/json", type: "text" });
  }
}

// ---------------------------------------------------------------------------
// Traversal and matching
// ---------------------------------------------------------------------------

function* eachRequest(items: ReadonlyArray<PostmanItem>): Generator<PostmanItem> {
  for (const item of items) {
    if (item.item) {
      yield* eachRequest(item.item);
      continue;
    }
    if (item.request) yield item;
  }
}

function matchesAny(
  item: PostmanItem,
  patterns: ReadonlyArray<RegExp>,
  methods: ReadonlyArray<string>,
): boolean {
  const method = item.request?.method?.toUpperCase();
  if (!method || !methods.includes(method)) return false;
  const uri = stripQueryAndHost(item.request?.url?.raw ?? "");
  return patterns.some((p) => p.test(uri));
}

/** Removes the host (`{{baseUrl}}`) and the query to compare only the path. */
function stripQueryAndHost(raw: string): string {
  const withoutQuery = raw.split("?")[0] ?? "";
  return withoutQuery.replace(/^\{\{[^}]+\}\}/, "");
}

/**
 * Last resort: if the host declared `loginEndpointName`, it searches by exact
 * name. This covers projects with unconventional login routes.
 */
function detectByName(
  collection: PostmanCollection,
  loginEndpointName?: string,
): IAuthFlow | null {
  if (!loginEndpointName) return null;
  for (const item of eachRequest(collection.item ?? [])) {
    if (item.name === loginEndpointName) {
      return { login: item, refresh: null, logout: null };
    }
  }
  return null;
}

