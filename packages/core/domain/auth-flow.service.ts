/**
 * Authentication flow for the collection.
 *
 * The goal is that, after importing the collection, the user fills in their
 * credentials once in the environment, runs Login, and everything else works
 * without touching the token again.
 *
 * `attachLoginAutoToken` used to exist, but in practice it never activated
 * (measured: 0 of 11 example projects) for two reasons:
 *
 *   1. It required a manually configured `tokenResponsePath` and exited through
 *      the back door with `if (!tokenPath) return;`.
 *   2. It searched for the login endpoint by comparing the item's NAME against
 *      ["login", "authenticate", …], while the names generated by the
 *      builder are "Create Login", "/POST auth/login", "/api_login"…
 *
 * Here, login is detected by method + URI, which is stable across frameworks,
 * and the script tries the usual response paths at runtime instead of
 * requiring them to be declared.
 */
import type {
  PostmanCollection,
  PostmanItem,
} from "../../contracts/interfaces/core/postman.interface.js";
import type { IAuthFlow } from "../../contracts/interfaces/core/discovery.interface.js";
import type { IApplyAuthFlowOptions } from "../../contracts/interfaces/core/domain.interface.js";
import type { IMissingCredentialsWarning } from "../../contracts/interfaces/cli/auth-warning.interface.js";
import { AUTH_PASSWORD_VARIABLE, AUTH_TOKEN_VARIABLE, AUTH_USERNAME_VARIABLE } from "../../contracts/constants/core/auth.constant.js";

/** URI suffixes that identify each step in the cycle. */
const LOGIN_URI_PATTERNS = [
  /\/login\/?$/i,
  /\/signin\/?$/i,
  /\/sign-in\/?$/i,
  /\/authenticate\/?$/i,
  /\/auth\/token\/?$/i,
  /\/oauth\/token\/?$/i,
  /\/sessions?\/?$/i,
];

/**
 * If the project exposes a session endpoint, based on the specs.
 *
 * `detectAuthFlow` answers the same question but for the **already-built
 * collection**, and some callers need to know before building it: the
 * authentication scheme determines which headers each request carries, so it
 * cannot be resolved afterward.
 *
 * It intentionally shares patterns with `detectAuthFlow`. If two lists of
 * login routes drift, the collection could say there is bearer while the flow
 * wires no token, or the other way around.
 */
export function hasLoginEndpoint(
  specs: ReadonlyArray<{ method: string; uri: string }>,
): boolean {
  return specs.some(
    (s) =>
      s.method.toUpperCase() === "POST" &&
      LOGIN_URI_PATTERNS.some((re) => re.test(s.uri)),
  );
}
const REFRESH_URI_PATTERNS = [/\/refresh\/?$/i, /\/auth\/refresh\/?$/i, /\/token\/refresh\/?$/i];
const LOGOUT_URI_PATTERNS = [/\/logout\/?$/i, /\/signout\/?$/i, /\/sign-out\/?$/i];

/**
 * Paths where the token usually appears in the response, in order of
 * probability. The script tries all of them at runtime: it is more robust
 * than asking the user to figure out which one applies.
 */
const TOKEN_RESPONSE_PATHS = [
  "access_token",
  "token",
  "accessToken",
  "data.access_token",
  "data.token",
  "data.accessToken",
  "jwt",
  "id_token",
];

/** Fields in the login body that represent the username. */
const USERNAME_FIELDS = ["email", "username", "user", "login", "correo", "usuario"];
/** Fields in the login body that represent the password. */
const PASSWORD_FIELDS = ["password", "passwd", "pass", "secret", "contrasena", "contraseña"];

/**
 * Locates the login, refresh, and logout endpoints in the collection.
 * Returns `null` if the project has none.
 */
export function detectAuthFlow(collection: PostmanCollection): IAuthFlow | null {
  const requests = [...eachRequest(collection.item ?? [])];

  const login = requests.find((i) => matchesAny(i, LOGIN_URI_PATTERNS, ["POST"])) ?? null;
  const refresh = requests.find((i) => matchesAny(i, REFRESH_URI_PATTERNS, ["POST"])) ?? null;
  const logout =
    requests.find((i) => matchesAny(i, LOGOUT_URI_PATTERNS, ["POST", "GET", "DELETE"])) ?? null;

  if (!login && !refresh && !logout) return null;
  return { login, refresh, logout };
}

/**
 * Wires the authentication flow onto an already-built collection:
 *
 *   - Login and refresh save the token when they respond with 2xx.
 *   - The login body references `{{authUsername}}` / `{{authPassword}}`.
 *   - Logout clears the token.
 *   - The flow is documented in the login description.
 *
 * Returns the applied flow, or `null` if the collection has no auth.
 */
export function applyAuthFlow(
  collection: PostmanCollection,
  options: IApplyAuthFlowOptions = {},
): IAuthFlow | null {
  const flow = detectAuthFlow(collection) ?? detectByName(collection, options.loginEndpointName);
  if (!flow) return null;

  const paths = options.tokenResponsePath?.trim()
    ? [options.tokenResponsePath.trim()]
    : TOKEN_RESPONSE_PATHS;

  // It is **added** to the array, not replaced. The builder has already put
  // assertions on each request, and assigning the whole array would wipe
  // them out exactly in the three endpoints where they are most needed:
  // those in the session cycle.
  if (flow.login) {
    flow.login.event = [...(flow.login.event ?? []), tokenCaptureEvent(paths)];
    flow.login.description = LOGIN_DESCRIPTION;
    attachCredentialTemplate(flow.login);
  }
  if (flow.refresh) {
    flow.refresh.event = [...(flow.refresh.event ?? []), tokenCaptureEvent(paths)];
  }
  if (flow.logout) {
    flow.logout.event = [...(flow.logout.event ?? []), tokenClearEvent()];
  }

  return flow;
}

/**
 * Variables the environment needs for the auth flow.
 * They are added only if the collection has login.
 */
export function authEnvironmentVariables(): Array<{
  key: string;
  value: string;
  type: string;
}> {
  return [
    { key: AUTH_USERNAME_VARIABLE, value: "", type: "secret" },
    { key: AUTH_PASSWORD_VARIABLE, value: "", type: "secret" },
    { key: AUTH_TOKEN_VARIABLE, value: "", type: "secret" },
  ];
}

