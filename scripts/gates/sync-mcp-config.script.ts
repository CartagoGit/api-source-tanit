#!/usr/bin/env bun
/**
 * `bun run mcp:sync` — un solo sitio donde declarar los servidores MCP.
 *
 * Claude Code y VS Code leen ficheros distintos y con formatos
 * distintos, así que tener los dos a mano significa que en cuanto
 * cambias uno el otro se queda viejo y nadie se entera hasta que un
 * servidor no arranca:
 *
 *   .mcp.json          Claude Code   { "mcpServers": … }   rutas relativas
 *   .vscode/mcp.json   VS Code       { "servers": … }      ${workspaceFolder}
 *
 * Un enlace simbólico no sirve porque el contenido difiere, no solo la
 * ruta. Así que `.mcp.json` manda y este script deriva el de VS Code.
 *
 * Uso:
 *   bun run mcp:sync            regenera .vscode/mcp.json
 *   bun run mcp:sync --check    falla si han derivado (es `lint:mcp`)
 */
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { MCP_JSON, VSCODE_DIR, VSCODE_MCP_JSON, fromRoot } from "../helpers/root.helper.js";

/** Un servidor MCP, en lo que ambos formatos comparten. */
interface IServer {
  readonly type?: string;
  readonly command: string;
  readonly cwd?: string;
  readonly args?: readonly string[];
  readonly env?: Record<string, string>;
}

/**
 * Traduce una ruta relativa al proyecto a la variable de VS Code.
 *
 * Claude Code lanza el servidor con el cwd en la raíz del proyecto, así
 * que `.` y `./algo` funcionan tal cual. VS Code no garantiza el cwd:
 * necesita `${workspaceFolder}` explícito.
 */
function toVsCodeArg(arg: string): string {
  if (arg === ".") return "${workspaceFolder}";
  return arg
    .replace(/^--workspace=\.$/, "--workspace=${workspaceFolder}")
    .replace(/^(--[\w-]+=)\.\//, "$1${workspaceFolder}/")
    .replace(/^\.\//, "${workspaceFolder}/");
}

/** El fichero de VS Code que corresponde a un `.mcp.json` dado. */
function buildVsCodeConfig(source: { mcpServers: Record<string, IServer> }): string {
  const servers: Record<string, IServer> = {};
  for (const [name, server] of Object.entries(source.mcpServers)) {
    servers[name] = {
      ...server,
      cwd: "${workspaceFolder}",
      ...(server.args ? { args: server.args.map(toVsCodeArg) } : {}),
    };
  }
  // **JSON estricto, sin comentarios.** VS Code admite JSONC, pero este
  // fichero no lo lee sólo VS Code: el runtime de DelendAI lo parsea
  // al arrancar para migrar la configuración del host, y esa lectura es
  // con `JSON.parse`. Con un `//` delante, el arranque falla con
  // "Unrecognized token '/'", el servidor sale con código 1 y vuelve a
  // intentarlo — un bucle que se repite en cada reinicio y que el
  // usuario ve como "the delendai server stopped while handling this
  // request" sin que se diga por qué.
  //
  // JSON estricto es un subconjunto de JSONC: un fichero sin
  // comentarios lo lee todo el mundo, y uno con comentarios sólo lo
  // leen los que los saben quitar. El aviso de "no lo edites a mano"
  // vive en `CONTRIBUTING.md` y en el mensaje de este gate, que es
  // donde alguien lo va a encontrar de verdad.
  return `${JSON.stringify({ servers }, null, 2)}\n`;
}

/** Codex consumes TOML rather than VS Code JSON; both derive from .mcp.json. */
export function buildCodexConfig(source: { mcpServers: Record<string, IServer> }): string {
  const lines = [
    "# Generated by bun run mcp:sync from .mcp.json. Do not edit manually.",
    "# Disable the generic inherited server only in this trusted project.",
    "[mcp_servers.DelendAI]", "enabled = false", "",
  ];
  for (const [name, server] of Object.entries(source.mcpServers)) {
    lines.push(`[mcp_servers.${JSON.stringify(name)}]`,
      `command = ${JSON.stringify(server.command)}`,
      `args = ${JSON.stringify(server.args ?? [])}`,
      'cwd = "."', "enabled = true", "startup_timeout_sec = 30", "");
    if (server.env && Object.keys(server.env).length > 0) {
      lines.push(`[mcp_servers.${JSON.stringify(name)}.env]`);
      for (const [key, value] of Object.entries(server.env)) {
        lines.push(`${JSON.stringify(key)} = ${JSON.stringify(value)}`);
      }
      lines.push("");
    }
  }
  return lines.join("\n");
}

async function syncCodex(source: { mcpServers: Record<string, IServer> }, check: boolean): Promise<number> {
  const path = fromRoot(".codex", "config.toml");
  const expected = buildCodexConfig(source);
  const current = await readFile(path, "utf8").catch(() => null);
  if (check) {
    if (current === expected) return 0;
    console.error("lint:mcp — .codex/config.toml differs from .mcp.json; run bun run mcp:sync.");
    return 1;
  }
  await mkdir(fromRoot(".codex"), { recursive: true });
  await writeFile(path, expected);
  return 0;
}

/**
 * Por qué el fichero no se puede leer como JSON.
 *
 * `null` cuando sí se puede. La razón se nombra entera porque el
 * síntoma que ve el usuario —el servidor que no arranca— no dice
 * nada del fichero: sin este motivo, quien lo edited busca en el
 * sitio equivocado.
 */
export function strictJsonProblem(source: string): string | null {
  const trimmed = source.trimStart();
  if (trimmed.startsWith("//") || trimmed.startsWith("/*")) {
    return (
      "el fichero empieza por un comentario: no es JSON estricto y hay lectores " +
      "que sólo saben leer JSON (el runtime de DelendAI lo parsea al arrancar)"
    );
  }
  try {
    JSON.parse(source);
    return null;
  } catch (error) {
    return `no es JSON válido: ${error instanceof Error ? error.message : String(error)}`;
  }
}

export async function main(argv: string[] = process.argv.slice(2)): Promise<number> {
  const check = argv.includes("--check");

  let source: { mcpServers?: Record<string, IServer> };
  try {
    source = JSON.parse(await readFile(MCP_JSON, "utf8"));
  } catch (error) {
    console.error(`mcp:sync — no se pudo leer .mcp.json: ${String(error)}`);
    return 1;
  }
  if (!source.mcpServers || Object.keys(source.mcpServers).length === 0) {
    console.error("mcp:sync — .mcp.json no declara ningún servidor en `mcpServers`");
    return 1;
  }

  const expected = buildVsCodeConfig({ mcpServers: source.mcpServers });
  const current = await readFile(VSCODE_MCP_JSON, "utf8").catch(() => null);

  if (check) {
    if (current === null) {
      console.error(
        "lint:mcp — .vscode/mcp.json no existe.\n" +
          "  Los servidores MCP se declaran UNA vez, en .mcp.json.\n" +
          "  Ejecuta `bun run mcp:sync` para generar el de VS Code.",
      );
      return 1;
    }
    // Primero lo legible: un fichero que no se puede leer es un
    // problema más grave que uno que se ha quedado viejo, y el motivo
    // del arranque que se repite en el log vive aquí.
    const problem = strictJsonProblem(current);
    if (problem !== null) {
      console.error(
        `lint:mcp — .vscode/mcp.json ${problem}.\n` +
          "  Tiene que ser JSON estricto: hay lectores que sólo saben leer JSON.\n" +
          "  Ejecuta `bun run mcp:sync` para regenerarlo.",
      );
      return 1;
    }
    if (current === expected) {
      const names = Object.keys(source.mcpServers).join(", ");
      console.log(`lint:mcp — .vscode/mcp.json al día con .mcp.json (${names})`);
      return syncCodex({ mcpServers: source.mcpServers }, true);
    }
    console.error(
      "lint:mcp — .vscode/mcp.json no coincide con .mcp.json.\n" +
        "  Los servidores MCP se declaran UNA vez, en .mcp.json.\n" +
        "  Ejecuta `bun run mcp:sync` para regenerar el de VS Code.",
    );
    return 1;
  }

  await mkdir(VSCODE_DIR, { recursive: true });
  await writeFile(VSCODE_MCP_JSON, expected);
  console.log(
    current === expected
      ? "mcp:sync — .vscode/mcp.json ya estaba al día"
      : `mcp:sync — .vscode/mcp.json regenerado desde .mcp.json ` +
          `(${Object.keys(source.mcpServers).length} servidores)`,
  );
  return syncCodex({ mcpServers: source.mcpServers }, false);
}

if (import.meta.main) {
  process.exit(await main());
}
