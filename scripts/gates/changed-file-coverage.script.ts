import { existsSync, readFileSync } from "node:fs";
import { dirname, isAbsolute, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { COVERAGE_METRICS, COVERAGE_THRESHOLDS, type CoverageScope } from "./coverage-policy.constant.js";
import type { IChangedCoverageResult } from "../../packages/contracts/interfaces/quality/changed-file-coverage.interface.js";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const SUMMARY_PATH = resolve(ROOT, "build/coverage/coverage-summary.json");
const SOURCE_FILE = /\.(?:[cm]?[jt]sx?)$/;

function normalizePath(file: string): string {
  const absolute = isAbsolute(file) ? file : resolve(ROOT, file);
  return relative(ROOT, absolute).split(sep).join("/");
}

function scopeFor(path: string): CoverageScope | undefined {
  if (path.startsWith("packages/core/")) return "core";
  if (path.startsWith("packages/frameworks/")) return "frameworks";
  if (path.startsWith("packages/cli/") || path.startsWith("packages/ui/") || path.startsWith("scripts/")) return "cli";
  return undefined;
}

function isMetric(value: unknown): value is { readonly total: number; readonly covered: number; readonly pct: number } {
  if (typeof value !== "object" || value === null) return false;
  const metric = value as Record<string, unknown>;
  const total = metric.total as number;
  const covered = metric.covered as number;
  const pct = metric.pct as number;
  return Number.isInteger(total) && Number.isInteger(covered) && Number.isFinite(pct) &&
    total >= 0 && covered >= 0 && covered <= total && pct >= 0 && pct <= 100 &&
    (total === 0 ? covered === 0 && pct === 100 : Math.abs(pct - (covered / total) * 100) < 0.01);
}

/** Fails closed if Vitest omitted a changed file or emitted incomplete metrics. */
export function evaluateChangedFileCoverage(
  changedFiles: readonly string[],
  summary: unknown,
): IChangedCoverageResult {
  const measurable = changedFiles
    .map(normalizePath)
    .filter(path => SOURCE_FILE.test(path) && scopeFor(path) !== undefined);
  if (measurable.length === 0) return { status: "NOT_APPLICABLE", failures: [] };
  if (typeof summary !== "object" || summary === null || Array.isArray(summary)) {
    return { status: "FAIL", failures: ["changed coverage — summary is missing or malformed"] };
  }

  const entries = summary as Record<string, unknown>;
  const normalizedEntries = new Map(Object.entries(entries).filter(([key]) => key !== "total").map(([key, value]) => [normalizePath(key), value]));
  const failures: string[] = [];
  const floorShortfalls: string[] = [];
  for (const path of measurable) {
    const scope = scopeFor(path);
    if (!scope) continue;
    const raw = normalizedEntries.get(path);
    if (typeof raw !== "object" || raw === null) {
      failures.push(`changed coverage — missing changed production file: ${path}`);
      continue;
    }
    const metrics = raw as Record<string, unknown>;
    for (const metricName of COVERAGE_METRICS) {
      const metric = metrics[metricName];
      if (!isMetric(metric)) {
        failures.push(`changed coverage — ${path}.${metricName} has incomplete metrics`);
        continue;
      }
      const floor = COVERAGE_THRESHOLDS[scope][metricName];
      if (metric.pct < floor) floorShortfalls.push(`changed coverage — ${path}.${metricName} ${metric.pct}% < ${scope} floor ${floor}%`);
    }
  }
  if (failures.length > 0) return { status: "FAIL", failures };
  if (floorShortfalls.length > 0) return { status: "BELOW_FLOOR", failures: floorShortfalls };
  return { status: "PASS", failures: [] };
}

/** Read and validate the coverage report generated by the affected test run. */
export function runChangedFileCoverage(changedFiles: readonly string[], summaryPath = SUMMARY_PATH): IChangedCoverageResult {
  if (!existsSync(summaryPath)) return { status: "FAIL", failures: [`changed coverage — missing report: ${summaryPath}`] };
  try {
    return evaluateChangedFileCoverage(changedFiles, JSON.parse(readFileSync(summaryPath, "utf8")) as unknown);
  } catch (error) {
    return { status: "FAIL", failures: [`changed coverage — cannot read report: ${error instanceof Error ? error.message : String(error)}`] };
  }
}

/** Only a complete below-floor report triggers the aggregate safety gate. */
export async function executeAggregateFallback(
  result: IChangedCoverageResult,
  runAggregate: () => Promise<number>,
): Promise<number> {
  if (result.status === "PASS" || result.status === "NOT_APPLICABLE") return 0;
  if (result.status === "BELOW_FLOOR") return runAggregate();
  return 1;
}
